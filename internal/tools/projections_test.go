func buildProjectionFixture(t *testing.T) *index.Index {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		"go.mod": "module example.com/proj\n\ngo 1.23\n",
		"modules/alpha/alpha.go": `package alpha

type API interface{ Value() int }

func Normal() int { return 1 }

func AlsoNormal() int { return 2 }

func ThirdNormal() int { return 3 }

const Max = 10
`,
		"modules/alpha/dto.gen.go": `// Code generated by fixture. DO NOT EDIT.
package alpha

func GeneratedHotspot(x int) int {
	if x > 0 {
		return 1
	}
	if x < 0 {
		return -1
	}
	return 0
}

func GeneratedAPI() int { return 4 }
`,
		"modules/beta/beta.go": `package beta

import "example.com/proj/modules/alpha"

func Use() int { return alpha.Normal() }
`,
	}
	for name, body := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	idx, err := index.Build(root)
	if err != nil {
		t.Fatal(err)
	}
	return idx
}

func projectionTool(t *testing.T, idx *index.Index, name string, summaries Summaries) mcp.Tool {
	t.Helper()
	for _, tool := range New(staticIndexer{idx: idx}, render.NewRegistry(), summaries) {
		if tool.Name == name {
			return tool
		}
	}
	t.Fatalf("%s not registered", name)
	return mcp.Tool{}
}

func TestCodebaseMapCompactAndFull(t *testing.T) {
	tool := projectionTool(t, buildProjectionFixture(t), "get_codebase_map", nil)

	text, failed := tool.Run(context.Background(), map[string]any{
		"format": "json", "top_modules": float64(1),
	})
	if failed {
		t.Fatal(text)
	}
	var compact struct {
		Modules []struct {
			Name             string `json:"name"`
			GeneratedSymbols int    `json:"generated_symbols"`
		} `json:"modules"`
		TotalModules   int    `json:"total_modules"`
		OmittedModules int    `json:"omitted_modules"`
		Truncated      bool   `json:"truncated"`
		TotalCount     int    `json:"total_count"`
		Hint           string `json:"hint"`
	}
	if err := json.Unmarshal([]byte(text), &compact); err != nil {
		t.Fatal(err)
	}
	if len(compact.Modules) != 1 || compact.TotalModules != 2 || compact.OmittedModules != 1 {
		t.Fatalf("modules = %+v total=%d omitted=%d", compact.Modules, compact.TotalModules, compact.OmittedModules)
	}
	if !compact.Truncated || compact.TotalCount != 2 || !strings.Contains(compact.Hint, "top_modules") {
		t.Fatalf("metadata = %+v", compact)
	}
	if compact.Modules[0].Name != "alpha" || compact.Modules[0].GeneratedSymbols == 0 {
		t.Fatalf("top module = %+v", compact.Modules[0])
	}

	text, failed = tool.Run(context.Background(), map[string]any{
		"format": "json", "detail": "full",
	})
	if failed {
		t.Fatal(text)
	}
	var full struct {
		Modules []json.RawMessage `json:"modules"`
	}
	if err := json.Unmarshal([]byte(text), &full); err != nil {
		t.Fatal(err)
	}
	if len(full.Modules) != 2 {
		t.Fatalf("full modules = %d", len(full.Modules))
	}
}

