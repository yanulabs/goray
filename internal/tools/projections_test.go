func TestSummaryContextNotFoundVersusNotEligible(t *testing.T) {
	idx := buildProjectionFixture(t)
	tool := projectionTool(t, idx, "get_summary_context", fakeSummaries{path: ":memory:"})

	text, failed := tool.Run(context.Background(), map[string]any{"symbol": "Nope"})
	if !failed {
		t.Fatalf("unknown symbol must fail: %s", text)
	}
	var missing struct {
		Error           string   `json:"error"`
		ExpectedFormats []string `json:"expected_formats"`
	}
	if err := json.Unmarshal([]byte(text), &missing); err != nil {
		t.Fatal(err)
	}
	if missing.Error != "symbol_not_found" || len(missing.ExpectedFormats) == 0 {
		t.Fatalf("not found payload = %+v", missing)
	}

	text, failed = tool.Run(context.Background(), map[string]any{"symbol_id": "modules/alpha.Max"})
	if failed {
		t.Fatalf("known non-summarizable symbol must return not_eligible: %s", text)
	}
	var notEligible struct {
		SyncState          string `json:"sync_state"`
		ParentPackageID    string `json:"parent_package_id"`
		ParentModuleID     string `json:"parent_module_id"`
		Note               string `json:"note"`
		ParentPackageCache *bool  `json:"parent_package_summary_cached"`
	}
	if err := json.Unmarshal([]byte(text), &notEligible); err != nil {
		t.Fatal(err)
	}
	if notEligible.SyncState != "not_eligible" || notEligible.ParentPackageID != "pkg:example.com/proj/modules/alpha" || notEligible.ParentModuleID != "mod:alpha" {
		t.Fatalf("not_eligible payload = %+v", notEligible)
	}
	if notEligible.ParentPackageCache == nil || *notEligible.ParentPackageCache {
		t.Fatalf("parent cache flag = %+v", notEligible.ParentPackageCache)
	}
	if !strings.Contains(notEligible.Note, "not eligible") {
		t.Fatalf("note = %q", notEligible.Note)
	}

	text, failed = tool.Run(context.Background(), map[string]any{"symbol_id": "modules/alpha"})
	if !failed {
		t.Fatalf("package target must fail: %s", text)
	}
}
