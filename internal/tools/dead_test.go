package tools

import (
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"

	"github.com/yanulabs/goray/internal/index"
	"github.com/yanulabs/goray/internal/mcp"
	"github.com/yanulabs/goray/internal/render"
)

type staticIndexer struct {
	idx    *index.Index
	status index.Status
}

func (s staticIndexer) Wait(context.Context) (*index.Index, error) { return s.idx, nil }
func (s staticIndexer) Status() index.Status {
	if s.status.IndexState == "" {
		s.status.IndexState = index.StateReady
	}
	return s.status
}
func (s staticIndexer) Root() string     { return s.idx.RootDir }
func (s staticIndexer) Rebuild() error   { return nil }

func buildToolFixture(t *testing.T) *index.Index {
	t.Helper()
	dir := t.TempDir()
	files := map[string]string{
		"go.mod": "module example.com/tooltest\n\ngo 1.23\n",
		"pkg/pub/pub.go": `package pub

func ExportedDead() {}
func unexportedDead() {}
`,
		"internal/core/core.go": `package core

func ExportedInInternalDead() {}
`,
		"modules/tools/scratch.go": `package tools

func noisyDead() {}
`,
		"gen/g.go": "// Code generated by tool. DO NOT EDIT.\n\npackage gen\n\nfunc GeneratedDead() {}\n",
	}
	for name, body := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	idx, err := index.Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	return idx
}

func namedTool(t *testing.T, name string) mcp.Tool {
	t.Helper()
	for _, tool := range New(staticIndexer{idx: buildToolFixture(t)}, render.NewRegistry(), nil) {
		if tool.Name == name {
			return tool
		}
	}
	t.Fatalf("tool %s not registered", name)
	return mcp.Tool{}
}

func runToolJSON(t *testing.T, tool mcp.Tool, args map[string]any) map[string]any {
	t.Helper()
	text, failed := tool.Run(context.Background(), args)
	if failed {
		t.Fatalf("tool failed: %s", text)
	}
	var out map[string]any
	if err := json.Unmarshal([]byte(text), &out); err != nil {
		t.Fatalf("invalid JSON %q: %v", text, err)
	}
	return out
}

func TestDeadCodeToolFiltersAndGrouping(t *testing.T) {
	tool := namedTool(t, "get_dead_code")
	out := runToolJSON(t, tool, nil)
	if out["total_candidates"] != float64(3) {
		t.Fatalf("default total = %v, want 3", out["total_candidates"])
	}
	candidates, _ := out["candidates"].([]any)
	names := map[string]bool{}
	for _, raw := range candidates {
		item, _ := raw.(map[string]any)
		names[item["name"].(string)] = true
		for _, key := range []string{"exported", "generated"} {
			if _, ok := item[key]; !ok {
				t.Fatalf("candidate missing %s: %v", key, item)
			}
		}
	}
	for _, want := range []string{"unexportedDead", "ExportedInInternalDead", "noisyDead"} {
		if !names[want] {
			t.Fatalf("%s missing from %v", want, names)
		}
	}
	if names["ExportedDead"] || names["GeneratedDead"] {
		t.Fatalf("default should exclude public exported and generated: %v", names)
	}

	out = runToolJSON(t, tool, map[string]any{"include_exported": true, "include_generated": true})
	if out["total_candidates"] != float64(5) {
		t.Fatalf("inclusive total = %v, want 5", out["total_candidates"])
	}

	out = runToolJSON(t, tool, map[string]any{"module": "tools"})
	if out["total_candidates"] != float64(1) {
		t.Fatalf("module total = %v", out["total_candidates"])
	}
	out = runToolJSON(t, tool, map[string]any{"exclude_modules": []any{"tools"}})
	if out["total_candidates"] != float64(2) {
		t.Fatalf("exclude total = %v", out["total_candidates"])
	}

	out = runToolJSON(t, tool, map[string]any{"group_by": "module", "limit": float64(1)})
	groups, _ := out["groups"].([]any)
	if len(groups) != 1 {
		t.Fatalf("grouped limit = %d, want 1", len(groups))
	}
	first, _ := groups[0].(map[string]any)
	if first["group"] != "internal/core" || first["count"] != float64(1) {
		t.Fatalf("group = %v", first)
	}
	if _, ok := out["candidates"]; ok {
		t.Fatal("grouped output must not contain flat candidates")
	}

	if _, failed := tool.Run(context.Background(), map[string]any{"group_by": "bad"}); !failed {
		t.Fatal("invalid group_by should fail")
	}

	// The registry count changed because get_hotspots is registered later;
	// verify the dead-code tool itself is still present exactly once.
	count := 0
	for _, item := range New(staticIndexer{idx: buildToolFixture(t)}, render.NewRegistry(), nil) {
		if item.Name == "get_dead_code" {
			count++
		}
	}
	if count != 1 {
		t.Fatalf("get_dead_code registered %d times", count)
	}
}
