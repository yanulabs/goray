func TestPackageSetDeduplicatesAndSortsVariants(t *testing.T) {
	set := newPackageSet()
	set.add([]*packages.Package{
		nil,
		{ID: "example.com/m/pkg", PkgPath: "example.com/m/pkg", Name: "pkg"},
		{ID: "example.com/m/pkg [example.com/m/pkg.test]", PkgPath: "example.com/m/pkg.test", Name: "main", ForTest: "example.com/m/pkg"},
		{ID: "example.com/m/pkg_test [example.com/m/pkg.test]", PkgPath: "example.com/m/pkg_test", Name: "pkg_test", ForTest: "example.com/m/pkg"},
	})
	set.add([]*packages.Package{
		{ID: "example.com/m/pkg", PkgPath: "example.com/m/pkg", Name: "pkg"},
		{ID: "example.com/a/pkg", PkgPath: "example.com/a/pkg", Name: "pkg"},
		{ID: "example.com/m/pkg [example.com/m/pkg.test]", PkgPath: "example.com/m/pkg", Name: "pkg", ForTest: "example.com/m/pkg"},
		{ID: "example.com/m/pkg_test [example.com/m/pkg.test]", PkgPath: "example.com/m/pkg_test", Name: "pkg_test", ForTest: "example.com/m/pkg"},
	})

	production, tests := set.sorted()
	if len(production) != 2 || production[0].PkgPath != "example.com/a/pkg" || production[1].PkgPath != "example.com/m/pkg" {
		t.Fatalf("production packages = %+v", production)
	}
	if len(tests) != 2 || tests[0].ID != "example.com/m/pkg [example.com/m/pkg.test]" || tests[1].ID != "example.com/m/pkg_test [example.com/m/pkg.test]" {
		t.Fatalf("test variants = %+v", tests)
	}
}

func TestPackageLoadErrorsReportsIncompletePackages(t *testing.T) {
	err := packageLoadErrors([]*packages.Package{
		{PkgPath: "example.com/m/broken", GoFiles: []string{"broken.go"}, Errors: []packages.Error{{Msg: "syntax error"}}},
		{PkgPath: "example.com/m/testonly"},
	})
	var loadErr *LoadError
	if !errors.As(err, &loadErr) {
		t.Fatalf("error = %T, want *LoadError", err)
	}
	want := []string{
		"example.com/m/broken: -: syntax error",
		"example.com/m/broken: incomplete syntax or type information",
	}
	if !reflect.DeepEqual(loadErr.Errors, want) {
		t.Fatalf("load errors = %v, want %v", loadErr.Errors, want)
	}
	if !strings.Contains(loadErr.Error(), strings.Join(want, "\n")) {
		t.Fatalf("formatted error = %q", loadErr.Error())
	}
}

func TestCollectTestLoadErrorsDeduplicatesAndSorts(t *testing.T) {
	got := collectTestLoadErrors([]*packages.Package{
		{PkgPath: "example.com/m", Errors: []packages.Error{{Msg: "production error"}}},
		{PkgPath: "example.com/m", ForTest: "example.com/m", Errors: []packages.Error{{Msg: "zeta"}, {Msg: "zeta"}}},
		{PkgPath: "example.com/m_test", ForTest: "example.com/m", Errors: []packages.Error{{Msg: "alpha"}, {Msg: "zeta"}}},
	})
	want := []string{"example.com/m: -: zeta", "example.com/m_test: -: alpha", "example.com/m_test: -: zeta"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("test load errors = %v, want %v", got, want)
	}
}

func TestBuilderOwningModuleUsesLongestPathBoundary(t *testing.T) {
	b := newBuilder(newIndex("/repo", "example.com/m", []string{"example.com/m", "example.com/m/modules/nested"}, nil), "/repo")
	cases := []struct {
		pkg  string
		want string
		ok   bool
	}{
		{pkg: "example.com/m", want: "example.com/m", ok: true},
		{pkg: "example.com/m/modules/nested", want: "example.com/m/modules/nested", ok: true},
		{pkg: "example.com/m/modules/nested/pkg", want: "example.com/m/modules/nested", ok: true},
		{pkg: "example.com/m/modules/nested-other", want: "example.com/m", ok: true},
		{pkg: "example.com/m-other", ok: false},
	}
	for _, test := range cases {
		got, ok := b.owningModule(test.pkg)
		if got != test.want || ok != test.ok {
			t.Errorf("owningModule(%q) = %q, %v; want %q, %v", test.pkg, got, ok, test.want, test.ok)
		}
	}
}

func TestCollectFileMetricsSeparatesProductionGeneratedAndTests(t *testing.T) {
	root := t.TempDir()
	regular := filepath.Join(root, "regular.go")
	generated := filepath.Join(root, "generated.go")
	large := filepath.Join(root, "large.go")
	testFile := filepath.Join(root, "regular_test.go")
	files := map[string]string{
		regular:                          "package sample\n\nfunc Value() {}\n",
		generated:                        "// Code generated by fixture. DO NOT EDIT.\n\npackage sample\n",
		large:                            "package sample\n" + strings.Repeat("// padding\n", largeFileLOC),
		testFile:                         "package sample\n\n// test one\n// test two\n",
		filepath.Join(root, "notes.txt"): "ignored\n",
	}
	for path, body := range files {
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	idx := newIndex(root, "example.com/m", []string{"example.com/m"}, map[string]bool{"regular.go": true})
	b := newBuilder(idx, root)
	pi := &PkgInfo{Dir: root, ModuleArea: "sample"}
	pkg := &packages.Package{GoFiles: []string{regular, generated, large}}
	b.collectFileMetrics(pkg, pi)

	if pi.Files != 3 || pi.ProdFiles != 0 || pi.TestFiles != 1 {
		t.Fatalf("file counts = %+v", pi)
	}
	if pi.ProdLOC != 3+largeFileLOC+1 || pi.GeneratedFiles != 1 || pi.GeneratedLOC != 3 || pi.TestLOC != 4 {
		t.Fatalf("LOC metrics = %+v", pi)
	}
	if pi.UntrackedFiles != 1 {
		t.Fatalf("untracked files = %d", pi.UntrackedFiles)
	}
	if len(idx.LargeFiles) != 1 || idx.LargeFiles[0].Path != "large.go" || idx.LargeFiles[0].LOC != largeFileLOC+1 {
		t.Fatalf("large files = %+v", idx.LargeFiles)
	}
	mod := idx.Modules["sample"]
	if mod == nil || mod.Files != 3 || mod.ProdLOC != pi.ProdLOC || mod.GeneratedLOC != 3 || mod.UntrackedFiles != 1 || len(mod.LargeFiles) != 1 {
		t.Fatalf("module metrics = %+v", mod)
	}
}
