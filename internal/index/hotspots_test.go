func hotspotFixture(t *testing.T) *Index {
	t.Helper()
	dir := writeGoModule(t, map[string]string{
		"go.mod": "module example.com/hotspot\n\ngo 1.23\n",
		"pkg/pkg.go": `package pkg

func Direct() {}
func Middle() { Leaf() }
func Leaf() {}
func Never() {
	if true {
		if true {
			if true {
				return
			}
		}
	}
}

type Big struct {
	A int
	B int
	C int
}

func (b *Big) Read() int { return b.A }
`,
		"pkg/pkg_test.go": `package pkg

import "testing"

func TestDirect(t *testing.T) { Direct() }
func TestMiddle(t *testing.T) { Middle() }
`,
		"gen/gen.go": `// Code generated by tool. DO NOT EDIT.

package gen

func GeneratedHuge() {
	if true { if true { if true { if true { return } } } }
}
`,
	})
	idx, err := Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	return idx
}

func TestStaticTestCoverage(t *testing.T) {
	idx := hotspotFixture(t)
	prefix := "example.com/hotspot/pkg."
	for name, want := range map[string]bool{
		"Direct": true, "Middle": true, "Leaf": true, "Never": false,
	} {
		if got := idx.TestCovered[prefix+name]; got != want {
			t.Fatalf("TestCovered[%s] = %v, want %v", name, got, want)
		}
	}
}

func TestHotspotTargetsAndSorts(t *testing.T) {
	idx := hotspotFixture(t)

	funcs, total := idx.Hotspots(HotspotOptions{Target: "func", SortBy: "risk", Limit: 100})
	if total == 0 || len(funcs) != total {
		t.Fatalf("func hotspots = %d/%d", len(funcs), total)
	}
	for _, item := range funcs {
		if item.TestCovered == nil {
			t.Fatalf("func hotspot missing test_covered: %+v", item)
		}
		if item.Name == "GeneratedHuge" {
			t.Fatal("generated hotspot included by default")
		}
	}
	if funcs[0].Name != "Never" {
		t.Fatalf("highest-risk function = %s, want Never", funcs[0].Name)
	}
	for i := 1; i < len(funcs); i++ {
		if funcs[i-1].RiskScore < funcs[i].RiskScore {
			t.Fatalf("risk order broken: %+v then %+v", funcs[i-1], funcs[i])
		}
	}

	untested, total := idx.Hotspots(HotspotOptions{Target: "func", UntestedOnly: true, Limit: 100})
	untestedNames := map[string]bool{}
	for _, item := range untested {
		untestedNames[item.Name] = true
	}
	if total == 0 || !untestedNames["Never"] || untestedNames["Direct"] || untestedNames["Middle"] || untestedNames["Leaf"] {
		t.Fatalf("untested hotspots = %+v", untested)
	}

	withGenerated, _ := idx.Hotspots(HotspotOptions{Target: "func", IncludeGenerated: true, Limit: 100})
	found := false
	for _, item := range withGenerated {
		if item.Name == "GeneratedHuge" {
			found = true
		}
	}
	if !found {
		t.Fatalf("include_generated did not add generated hotspot: %+v", withGenerated)
	}

	for _, sortBy := range []string{"complexity", "loc", "fan_in"} {
		items, _ := idx.Hotspots(HotspotOptions{Target: "func", SortBy: sortBy, Limit: 100})
		for i := 1; i < len(items); i++ {
			key := func(item Hotspot) int {
				switch sortBy {
				case "complexity":
					return item.Complexity
				case "loc":
					return item.LOC
				default:
					return item.FanIn
				}
			}
			if key(items[i-1]) < key(items[i]) {
				t.Fatalf("%s order broken: %+v then %+v", sortBy, items[i-1], items[i])
			}
		}
	}

	files, total := idx.Hotspots(HotspotOptions{Target: "file", Limit: 100})
	if total == 0 || files[0].Kind != "file" {
		t.Fatalf("file hotspots = %+v", files)
	}
	types, total := idx.Hotspots(HotspotOptions{Target: "type", Limit: 100})
	if total == 0 || types[0].Name != "Big" || types[0].Fields != 3 || types[0].Methods != 1 || types[0].Complexity != 4 {
		t.Fatalf("type hotspots = %+v", types)
	}

	filtered, total := idx.Hotspots(HotspotOptions{
		Target: "func", Module: "gen", IncludeGenerated: true, MinComplexity: 3, Limit: 100,
	})
	if total != 1 || filtered[0].Name != "GeneratedHuge" {
		t.Fatalf("module/min_complexity filter = %+v", filtered)
	}
	excluded, total := idx.Hotspots(HotspotOptions{Target: "func", ExcludeModules: []string{"pkg"}, Limit: 100})
	if total != 0 {
		t.Fatalf("exclude_modules = %+v", excluded)
	}
	minLoc, total := idx.Hotspots(HotspotOptions{Target: "func", MinLoc: 1000, Limit: 100})
	if total != 0 {
		t.Fatalf("min_loc = %+v", minLoc)
	}
	limited, total := idx.Hotspots(HotspotOptions{Target: "func", Limit: 1})
	if len(limited) != 1 || total <= 1 {
		t.Fatalf("limit = %d, total = %d", len(limited), total)
	}
}

func TestTestHelperFunctionsSeedCoverage(t *testing.T) {
	dir := writeGoModule(t, map[string]string{
		"go.mod": "module example.com/helper\n\ngo 1.23\n",
		"pkg/p.go": `package pkg

func Target() {}
`,
		"pkg/p_test.go": `package pkg

import "testing"

func TestX(t *testing.T) { helper() }
func helper()           { Target() }
`,
	})
	idx, err := Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	if !idx.TestCovered["example.com/helper/pkg.Target"] {
		t.Fatal("production function reached through a test helper was not marked covered")
	}
}

func TestFileHotspotsFanInAndAggregateFilters(t *testing.T) {
	idx := hotspotFixture(t)
	items, _ := idx.Hotspots(HotspotOptions{Target: "file", SortBy: "fan_in", Limit: 100})
	var target Hotspot
	for _, item := range items {
		if item.Name == "pkg/pkg.go" {
			target = item
		}
	}
	if target.Name == "" {
		t.Fatalf("pkg/pkg.go missing from file hotspots: %+v", items)
	}
	if target.FanIn == 0 {
		t.Fatalf("file fan-in not aggregated: %+v", target)
	}

	full := target.LOC
	byMin, _ := idx.Hotspots(HotspotOptions{Target: "file", MinLoc: full, Limit: 100})
	if len(byMin) == 0 {
		t.Fatalf("min_loc should apply to aggregate file LOC (%d)", full)
	}
	above, _ := idx.Hotspots(HotspotOptions{Target: "file", MinLoc: full + 1, Limit: 100})
	if len(above) != 0 {
		t.Fatalf("min_loc above aggregate LOC should filter the file: %+v", above)
	}

	for _, sortBy := range []string{"loc", "complexity", "fan_in"} {
		items, _ := idx.Hotspots(HotspotOptions{Target: "file", SortBy: sortBy, Limit: 100})
		key := func(item Hotspot) int {
			switch sortBy {
			case "loc":
				return item.LOC
			case "complexity":
				return item.Complexity
			default:
				return item.FanIn
			}
		}
		for i := 1; i < len(items); i++ {
			if key(items[i-1]) < key(items[i]) {
				t.Fatalf("file %s order broken: %+v then %+v", sortBy, items[i-1], items[i])
			}
		}
	}
}
