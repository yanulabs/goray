package index

import (
	"os"
	"path/filepath"
	"slices"
	"testing"
)

func writeGoModule(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func deadFixture(t *testing.T) *Index {
	t.Helper()
	dir := writeGoModule(t, map[string]string{
		"go.mod": "module example.com/deadtest\n\ngo 1.23\n",
		"pkg/pub/pub.go": `package pub

import (
	"sort"
)

type Value struct{ N int }

func (v Value) String() string { return "v" }
func (v Value) MarshalJSON() ([]byte, error) { return nil, nil }
func (v *Value) Error() string { return "e" }
func (v Value) notAnInterfaceMethod() {}

type Seq []int

func (s Seq) Len() int              { return len(s) }
func (s Seq) Less(i, j int) bool    { return s[i] < s[j] }
func (s Seq) Swap(i, j int)         { s[i], s[j] = s[j], s[i] }
var _ sort.Interface = Seq{}

type Greeter interface{ Greet() string }
type GreeterImpl struct{}
func (g GreeterImpl) Greet() string { return "hi" }
var _ Greeter = GreeterImpl{}

type Poker interface{ Poke() }
type PtrImpl struct{}
func (p *PtrImpl) Poke() {}
var _ Poker = (*PtrImpl)(nil)

func ExportedDead() {}
func unexportedDead() {}
func called() {}
func caller() { called() }
`,
		"internal/core/core.go": `package core

func ExportedInInternalDead() {}
func unexportedInInternalDead() {}
func live() {}
func Live() { live() }
`,
		"modules/tools/scratch.go": `package tools

func noisyDead() {}
`,
		"gen/generated.go": `// Code generated by tool. DO NOT EDIT.

package gen

func GeneratedDead() {}
`,
		"gen/nonstandard.go": `// THIS FILE IS AUTO-GENERATED. DO NOT EDIT.

package gen

func NonStandardDead() {}
`,
	})
	idx, err := Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	return idx
}

func deadNames(symbols []*Symbol) []string {
	out := make([]string, 0, len(symbols))
	for _, sym := range symbols {
		out = append(out, sym.Name)
	}
	return out
}

func TestDeadCodeFilters(t *testing.T) {
	idx := deadFixture(t)
	names := deadNames(idx.DeadCode(DeadCodeOptions{}))

	for _, want := range []string{"unexportedDead", "ExportedInInternalDead", "unexportedInInternalDead", "noisyDead", "notAnInterfaceMethod", "caller"} {
		if !slices.Contains(names, want) {
			t.Fatalf("%s should be dead; got %v", want, names)
		}
	}
	for _, suppressed := range []string{"String", "MarshalJSON", "Error", "Len", "Less", "Swap", "Greet", "Poke", "ExportedDead", "GeneratedDead", "NonStandardDead", "called"} {
		if slices.Contains(names, suppressed) {
			t.Fatalf("%s should not be dead; got %v", suppressed, names)
		}
	}

	withGenerated := deadNames(idx.DeadCode(DeadCodeOptions{IncludeGenerated: true, IncludeExported: true}))
	for _, want := range []string{"GeneratedDead", "NonStandardDead"} {
		if !slices.Contains(withGenerated, want) {
			t.Fatalf("%s missing with include_generated; got %v", want, withGenerated)
		}
	}

	withExported := deadNames(idx.DeadCode(DeadCodeOptions{IncludeExported: true}))
	if !slices.Contains(withExported, "ExportedDead") {
		t.Fatalf("ExportedDead missing with include_exported; got %v", withExported)
	}

	moduleOnly := deadNames(idx.DeadCode(DeadCodeOptions{Module: "tools"}))
	if len(moduleOnly) != 1 || moduleOnly[0] != "noisyDead" {
		t.Fatalf("module filter = %v", moduleOnly)
	}
	excluded := deadNames(idx.DeadCode(DeadCodeOptions{ExcludeModules: []string{"tools"}}))
	if slices.Contains(excluded, "noisyDead") {
		t.Fatalf("exclude_modules did not remove noisyDead: %v", excluded)
	}

	groups := GroupSymbolsBy(idx.DeadCode(DeadCodeOptions{}), "module")
	if len(groups["internal/core"]) == 0 || len(groups["tools"]) != 1 {
		t.Fatalf("module groups = %v", deadNames(groups["internal/core"]))
	}
	packages := GroupSymbolsBy(idx.DeadCode(DeadCodeOptions{}), "package")
	if len(packages["pkg/pub"]) == 0 {
		t.Fatalf("package groups = %v", packages)
	}
}

func TestImportedThirdPartyInterfaceSuppression(t *testing.T) {
	dir := writeGoModule(t, map[string]string{
		"go.mod": `module example.com/app

go 1.23

require example.com/ext v0.0.0

replace example.com/ext => ./ext
`,
		"ext/go.mod": "module example.com/ext\n\ngo 1.23\n",
		"ext/ext.go": `package ext

type Pinger interface{ Ping() }
`,
		"app.go": `package app

import "example.com/ext"

type Impl struct{}

func (Impl) Ping() {}

var _ ext.Pinger = Impl{}

func TrulyDead() {}
`,
	})
	idx, err := Build(dir)
	if err != nil {
		t.Fatal(err)
	}
	names := deadNames(idx.DeadCode(DeadCodeOptions{IncludeExported: true}))
	if slices.Contains(names, "Ping") {
		t.Fatalf("third-party interface method reported dead: %v", names)
	}
	if !slices.Contains(names, "TrulyDead") {
		t.Fatalf("unrelated function missing from dead code: %v", names)
	}
}

func TestGeneratedDetectionHeaders(t *testing.T) {
	cases := map[string]bool{
		"// Code generated by mockgen. DO NOT EDIT.\npackage a\n": true,
		"// Code generated by tool. DO NOT EDIT.\npackage a\n":    true,
		"// DO NOT EDIT\npackage a\n":                             true,
		"// Auto-generated file\npackage a\n":                     true,
		"// autogenerated\npackage a\n":                           true,
		"// Generated by protoc-gen-go\npackage a\n":              true,
		"/* generated by hand tooling */\npackage a\n":            true,
		"/*\nDO NOT EDIT\n*/\npackage a\n":                        true,
		"// This package is normal.\n// DO NOT EDIT\npackage a\n": true,
		"package a\n\n// DO NOT EDIT\nfunc F() {}\n":              false,
		"// a normal comment\npackage a\nfunc F() {}\n":           false,
	}
	for src, want := range cases {
		if got := isGenerated("x.go", []byte(src)); got != want {
			t.Fatalf("isGenerated(%q) = %v, want %v", src, got, want)
		}
	}
	if !isGenerated("x.gen.go", []byte("package x\n")) {
		t.Fatal(".gen.go not detected")
	}
}
